export const movies: Movie[] = baseMovies.map((movie) => ({
  ...movie,
  poster: movieMeta[movie.id]?.poster ?? null,
  rating: movieMeta[movie.id]?.rating ?? null,
  streaming: movieMeta[movie.id]?.streaming ?? [],
}));

export function justWatchUrl(title: string): string {
  return `https://www.justwatch.com/us/search?q=${encodeURIComponent(title)}`;
}

export function getMovieById(id: string): Movie | undefined {
  return movies.find((movie) => movie.id === id);
}

export const doomsdayMovie = movies.find((m) => m.id === "avengers-doomsday")!;

export const catalogMovies: Movie[] = movies.filter(
  (movie) => movie.status === "released",
);

export const journeyMovies: Movie[] = movies
  .filter((movie) => movie.isRequiredForDoomsday && movie.journeyOrder !== null)
  .sort((a, b) => (a.journeyOrder ?? 0) - (b.journeyOrder ?? 0));

export const upcomingMovies: Movie[] = movies
  .filter((movie) => movie.status === "upcoming")
  .sort((a, b) => (a.releaseDate ?? "9999").localeCompare(b.releaseDate ?? "9999"));

export const OFFICIAL_WATCHLIST_TAG = "Official Watchlist";

export const officialWatchlistMovies: Movie[] = journeyMovies.filter((movie) =>
  movie.tags.includes(OFFICIAL_WATCHLIST_TAG),
);

export const journeyExtraMovies: Movie[] = journeyMovies.filter(
  (movie) => !movie.tags.includes(OFFICIAL_WATCHLIST_TAG),
);
